export const translate = (text: string, language: AppLanguage = typeof localStorage !== 'undefined' && localStorage.getItem('quickStock_language') === 'km' ? 'km' : 'en') => language === 'km' ? translations[text] || text : text;

const LanguageContext = createContext<{ language: AppLanguage; setLanguage: (language: AppLanguage) => void; t: (text: string) => string }>({ language: 'en', setLanguage: () => {}, t: text => text });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>(() => localStorage.getItem('quickStock_language') === 'km' ? 'km' : 'en');
  useEffect(() => {
    localStorage.setItem('quickStock_language', language);
    document.documentElement.lang = language;
  }, [language]);
  return <LanguageContext.Provider value={{ language, setLanguage, t: text => language === 'km' ? translations[text] || text : text }}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);
